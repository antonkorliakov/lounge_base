import { describe, it, expect } from 'vitest'
import { SESSION_COOKIE_MAX_AGE_SECONDS } from '../session'
import { SESSION_TTL_DAYS } from '../team'

const DAY_SECONDS = 24 * 60 * 60

/**
 * Cookie-потолок и скользящий TTL — две разные политики (см. комментарии при
 * обеих константах), и связь между ними ровно одна: потолок должен быть
 * заметно больше окна, иначе активный проверяющий увидит экран входа посреди
 * работы — то, что `SESSION_TTL_DAYS`'s комментарий обещает не допускать.
 *
 * Тест держит именно это неравенство, а не сами числа: он не сравнивает
 * константу с собой и не запрещает менять ни одну из двух политик. Он падает
 * ровно в одном случае — когда TTL вырос (или потолок сжался) настолько, что
 * браузер перестаёт доживать до продления, и обещание тихо перестаёт
 * выполняться.
 */
describe('срок cookie против скользящего TTL сессии', () => {
  it('потолок одного входа кратно больше скользящего окна', () => {
    const windowSeconds = SESSION_TTL_DAYS * DAY_SECONDS

    expect(SESSION_COOKIE_MAX_AGE_SECONDS).toBeGreaterThanOrEqual(windowSeconds * 4)
  })

  it('потолок задан в секундах — единицах cookie `maxAge`, а не в днях', () => {
    // 90 дней в секундах. Пин на единицы, а не на политику: `maxAge` в
    // Set-Cookie измеряется в секундах, и число вроде 90 в этом поле было бы
    // потолком в девяносто секунд — вход, обрывающийся через полторы минуты.
    expect(SESSION_COOKIE_MAX_AGE_SECONDS).toBe(90 * DAY_SECONDS)
  })
})
