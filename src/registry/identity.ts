/**
 * Соответствие «паспорт лаунжа ↔ поля блока I» и всё, что из него чисто
 * выводится, — в собственном ЛИСТОВОМ модуле без единого value-импорта, по
 * тому же доводу, что `registry/iata.ts` (см. историю там): список
 * производных полей теперь нужен и КЛИЕНТСКИМ компонентам формы заполнения
 * (`FillForm`/`FixesOnly` решают, какому ключу рисовать read-only показ, а
 * какому — исправление кода), а тащить в клиентский бандл весь `manage.ts` —
 * с drizzle, схемой БД и токенами — ради двух констант нельзя. `manage.ts`
 * ре-экспортирует всё отсюда, так что прежние серверные импорты остаются
 * правдой. Единственный импорт ниже — `import type`: тип стирается
 * компилятором (тот же приём, что `FlagReason` в `i18n/dictionaries.ts`),
 * слой БД в бандл не попадает.
 */
import type { DirectoryEntry } from './directory'

/** Колонки паспорта лаунжа, которые участвуют в предзаполнении, — ровно те,
 *  что принимает `createLounge` (плюс их nullability по `db/schema.ts`). */
export type IdentityColumns = {
  name: string
  provider: string | null
  country: string
  city: string
  airport: string
  iataCode: string
}

/**
 * Паспорт лаунжа ↔ анкетные поля блока I: то, что администратор уже набрал в
 * «Add lounge», оператор не должен набирать второй раз. ОДНА запись
 * соответствия на все его употребления — предзаполнение при создании
 * (`createLounge`), серверный расчёт «что показать под замком» на форме
 * заполнения (`lockedIdentityKeys`), синхронизация принятия
 * (`passportFieldsFrom` в `review/decide.ts`) и производные списки ниже;
 * рукописная копия списка на клиенте — ровно тот класс расползания, который
 * эта ветка ловит не первый раз (`EDITABLE_STATUSES`, `FLAG_REASONS`, …).
 *
 * `lockable: false` у названия — решение пользователя: название лаунжа
 * остаётся редактируемым оператором ВСЕГДА. Отсюда осознанная асимметрия,
 * и с синхронизацией паспорта на принятии она стала РЕЗЧЕ, а не исчезла:
 * `approveSubmission` теперь копирует в реестр, кроме классифицирующих
 * полей (III.6.*), ещё и принятые ответы паспорта — страну/город/аэропорт/
 * IATA (I.7–I.10, см. `passportFieldsFrom` в `review/decide.ts`), — но
 * НЕ название: правка I.2 оператором по-прежнему НЕ меняет `lounges.name`.
 * Строка реестра держит имя администратора, а экран проверки показывает оба
 * (заголовок — имя реестра, строка I.2 — ответ оператора), и расхождение
 * видно ревьюеру. Это существующее и принятое поведение, не побочный эффект
 * предзаполнения; на нём стоит и заголовок экрана проверки. `provider`
 * (I.3) в синхронизацию тоже не входит — не по принципиальному решению, как
 * имя, а потому, что согласованный разрыв касался четырёх полей, которыми
 * фильтруют реестр и выгрузку; колонка остаётся творением создания лаунжа.
 */
export const IDENTITY_PREFILL = [
  { column: 'name', fieldKey: 'I.2', lockable: false },
  { column: 'provider', fieldKey: 'I.3', lockable: true },
  { column: 'country', fieldKey: 'I.7', lockable: true },
  { column: 'city', fieldKey: 'I.8', lockable: true },
  { column: 'airport', fieldKey: 'I.9', lockable: true },
  { column: 'iataCode', fieldKey: 'I.10', lockable: true },
] as const satisfies readonly {
  column: keyof IdentityColumns
  fieldKey: string
  lockable: boolean
}[]

/**
 * Колонки, которые ПОСТАВЛЯЕТ справочник аэропортов, — ровно ключи
 * `DirectoryEntry`, и `satisfies Record<keyof DirectoryEntry, true>` держит
 * это компилятором в обе стороны: колонка, добавленная в справочник, не
 * может не попасть сюда, а колонка не из справочника — попасть. Именно эта
 * привязка делает `DERIVED_PREFILL` производным от одного источника, а не
 * вторым рукописным списком «I.7/I.8/I.9»: производные поля — это ПО
 * ОПРЕДЕЛЕНИЮ то, что справочник выводит из кода (I.3 provider тоже
 * lockable, но справочник его не знает — и сюда он не попадает).
 */
const DIRECTORY_COLUMNS = {
  country: true,
  city: true,
  airport: true,
} as const satisfies Record<keyof DirectoryEntry, true>

/** Записи соответствия, чьи колонки выводятся из кода IATA справочником, —
 *  с сужением типа колонки до `keyof DirectoryEntry`, чтобы запись значений
 *  справочника по этим записям (`saveOperatorField` в `manage.ts`) не
 *  требовала каста. */
export const DERIVED_PREFILL = IDENTITY_PREFILL.filter(
  (entry): entry is (typeof IDENTITY_PREFILL)[number] & { column: keyof DirectoryEntry } =>
    entry.column in DIRECTORY_COLUMNS,
)

/**
 * Ключи полей анкеты, которые оператор НЕ пишет напрямую НИКОГДА — ни в
 * основном проходе, ни на экране правок, ни постом по сети: их значения
 * выводятся из кода IATA (`I.10`) справочником, и исправляются они
 * исправлением КОДА. Серверные ворота — `saveOperatorField`
 * (`registry/manage.ts`); клиентские показы обязаны не предлагать того, в
 * чём сервер откажет.
 */
export const DERIVED_FIELD_KEYS: readonly string[] = DERIVED_PREFILL.map(
  (entry) => entry.fieldKey,
)

/** Ключ поля кода IATA — «водителя» производной тройки, из той же записи
 *  соответствия (`find` по колонке, не литерал: литерал был бы второй
 *  записью того, что уже записано в `IDENTITY_PREFILL`). */
export const IATA_FIELD_KEY: string = IDENTITY_PREFILL.find(
  (entry) => entry.column === 'iataCode',
)!.fieldKey

/**
 * Какие поля блока I показывать оператору под замком (только чтение) в
 * ОСНОВНОМ проходе формы. Правило по каждому полю: колонка паспорта непуста
 * И сохранённый ответ анкеты дословно (после trim) совпадает с ней. Обе
 * половины обязательны, и это не перестраховка:
 *
 *  - «Колонка непуста» одна НЕ годится: лаунжи, заведённые до этой фичи
 *    (или ops-скриптом с пустой страной), имеют непустые колонки и НИ ОДНОГО
 *    предзаполненного ответа — замок на пустом обязательном поле сделал бы
 *    анкету незаполнимой и неотправляемой (тот самый класс «нужный человек
 *    не может дотянуться», за который проект уже платил Critical'ом).
 *  - «Ответ есть» одно не годится тоже: после того как ревьюер отметил
 *    поле, а оператор на экране правок исправил его, ответ расходится с
 *    колонкой, и подпись «заполнено вашей командой» стала бы ложью. Совпало
 *    — замок стоит; разошлось — замок растворяется, и основной проход тоже
 *    отдаёт поле в правку. Для производной тройки (I.7–I.9) этот расчёт
 *    больше не решает редактируемость — она read-only ВСЕГДА (см.
 *    `DERIVED_FIELD_KEYS`); для I.10 «замок растворился» означает, что
 *    основной проход показывает исправление кода через справочник, а не
 *    свободный ввод.
 *
 * Считается НА СЕРВЕРЕ (страница заполнения знает и лаунж, и ответы) и
 * передаётся клиенту готовым списком ключей.
 */
export function lockedIdentityKeys(
  lounge: IdentityColumns,
  fields: Record<string, unknown>,
): string[] {
  const locked: string[] = []
  for (const entry of IDENTITY_PREFILL) {
    if (!entry.lockable) continue
    const column = lounge[entry.column]
    if (column === null || column.trim() === '') continue
    const answer = fields[entry.fieldKey]
    if (typeof answer !== 'string') continue
    if (answer.trim() !== column.trim()) continue
    locked.push(entry.fieldKey)
  }
  return locked
}
