/**
 * Правило «как выглядит код IATA» — в собственном ЛИСТОВОМ модуле без единого
 * импорта. Родилось оно в `registry/manage.ts` (см. историю там: до него
 * правила не было нигде в системе), а переехало сюда, когда появился
 * справочник аэропортов: код теперь набирают и в клиентских формах кабинета
 * (`PassportFieldsEditor` решает, пора ли спрашивать справочник), а тащить в
 * клиентский бандл весь `manage.ts` — с drizzle, схемой БД и токенами — ради
 * одного регэкспа нельзя. Модуль без зависимостей одинаково доступен серверу,
 * клиенту и скриптам; `manage.ts` ре-экспортирует `normalizeIata`, так что
 * прежние серверные импорты остаются правдой.
 */

/**
 * Три латинские буквы, после trim/uppercase. Нормализация до валидации:
 * `ist` — опечатка регистра, а не другой код.
 */
const IATA_RE = /^[A-Z]{3}$/

/**
 * Единственная запись правила IATA в исполнимом виде: trim/uppercase, затем
 * проверка «ровно три латинские буквы»; не прошло — `null`, и что с этим
 * делать, решает вызывающий. Вызывающие обязаны ходить сюда, а не носить
 * свою копию регэкспа: `createLounge`/`updateLoungePassport` (null — отказ),
 * `passportFieldsFrom` (`review/decide.ts`; null — колонка пропускается при
 * синхронизации), `lookupAirport` и импорт справочника
 * (`registry/directory.ts`; null — «в справочнике такого нет» / негодная
 * строка TSV) и клиентский `PassportFieldsEditor` (null — код ещё не набран,
 * справочник не спрашивается). Разъехаться правило может только вместе с
 * этой функцией.
 */
export function normalizeIata(raw: string): string | null {
  const code = raw.trim().toUpperCase()
  return IATA_RE.test(code) ? code : null
}
