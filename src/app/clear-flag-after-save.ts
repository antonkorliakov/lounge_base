import { db } from '@/db/client'
import { clearFlagsFor } from '@/review/flags'

/**
 * Снимает замечание по только что исправленному ответу (и подтверждение его
 * блока — см. `clearFlagsFor`). Живёт в слое серверных действий/маршрутов, а
 * не в `saveFieldValue`/`saveServiceValue`/`attachPhoto`: иначе `submissions`
 * (или `photos`) начал бы зависеть от `review`, что запрещено границей
 * модулей. Этот слой и так знает про оба модуля — он и связывает их.
 *
 * Отдельный модуль, а не приватная функция внутри
 * `src/app/f/[token]/actions.ts`, потому что вызывающих несколько и они лежат
 * в разных файлах: серверные действия сохранения ответа (`saveFieldAction`,
 * `saveServiceAction`) и маршрут фото (`src/app/api/photos/route.ts`) — там и
 * загрузка, и удаление снимка. Точное число здесь не называется намеренно:
 * оно уже разошлось с кодом один раз (комментарий говорил «ТРИ», когда
 * вызывающих стало четыре — DELETE добавился вместе с кнопкой «убрать»), а
 * счётчик, который нужно править вручную при каждом новом вызове, — ровно тот
 * класс дефекта, который эта ветка ловит уже не первый раз. Кто именно
 * вызывает, всегда точно скажет поиск по имени функции.
 * Экспортировать её из `actions.ts` нельзя
 * даже технически: у файла с `'use server'` каждый экспорт становится
 * серверным действием, то есть публично вызываемой точкой входа — снятие
 * замечаний без всякой проверки токена. Поэтому одна реализация лежит здесь,
 * в обычном модуле, а не копируется в маршрут: копия «снимает флаг похожим
 * образом» ровно тот класс дефекта, который эта ветка ловит уже не первый
 * раз.
 *
 * **Почему провал этого шага НЕ превращается в отказ действия.** Значение
 * (или снимок) уже записано и закоммичено своей собственной транзакцией;
 * снятие замечания — вторая, отдельная транзакция (`saveFieldValue`,
 * `attachPhoto` и `clearFlagsFor` каждый открывают свою). Транзакции,
 * накрывающей оба вызова, здесь нет и быть не может: обе функции открывают
 * транзакцию внутри себя и не принимают чужой `Tx`, а прокинуть один `Tx`
 * через обе означало бы дать `submissions`/`photos` доступ к `review` (или
 * наоборот) — ровно ту зависимость, из-за которой эта связка вообще вынесена
 * в слой действий. Так что выбор не между «атомарно» и «нет», а только между
 * двумя способами сообщить о сбое второго шага, и выбран он осознанно:
 *
 *  - Вернуть `{ ok: false }` (или дать исключению уйти наверх) — значит
 *    показать заполняющему ошибку под ответом, который в базе уже лежит
 *    правильным. `queueDrain` (`src/web/useAutosave.ts`) трактует
 *    `{ ok: false }` как окончательный отказ: ключ удаляется из очереди
 *    (повтора не будет), попадает в `rejected`, статус формы становится
 *    `'rejected'` вместо `'saved'`, и `FixesOnly` рисует это сообщение
 *    прямо под полем через свой `fieldErrors`. Заполняющий читает «не
 *    сохранилось» про сохранённое и переписывает ответ заново. Исключение
 *    ведёт себя не лучше: `queueDrain` считает его сетевым, оставляет
 *    значение в очереди и показывает `'offline'` — сообщение, которое врёт
 *    о причине. Для маршрута фото то же самое ещё грубее: снимок уже лежит
 *    и в blob-хранилище, и в `photos`, а заполняющий увидел бы «не удалось
 *    загрузить» и загрузил бы его второй раз.
 *  - Вернуть `{ ok: true }` — значит принять единственное реальное
 *    последствие: на исправленном ответе останется висеть замечание ревьюера
 *    (и его блок останется в том же состоянии, что и до правки). Экран
 *    правок продолжит показывать эту карточку — с уже исправленным
 *    значением внутри, — и повторная отправка этим не блокируется
 *    (`submitSubmission` проверяет полноту, а не замечания). Ревьюер увидит
 *    замечание открытым и блок неподтверждённым, то есть посмотрит ответ
 *    заново — консервативная сторона: ничего не теряется и ничто не
 *    выглядит проверенным, не будучи проверенным.
 *
 * Второй вариант и выбран: вызывающий отвечает за ту запись, которую его
 * просили сделать, и она удалась. Сбой глушится здесь, а не уходит наверх,
 * иначе поведением по умолчанию стал бы третий, самый плохой вариант
 * (`'offline'` / голая 500 у маршрута). `console.error` оставляет его видимым
 * в логах сервера — молчаливой потери нет, просто она не адресована
 * заполняющему, который ничего с ней сделать не может.
 */
export async function clearFlagAfterSave(submissionId: string, key: string): Promise<void> {
  try {
    await clearFlagsFor(db(), submissionId, key)
  } catch (error) {
    console.error(
      `[fill] value for ${key} saved, but clearing its flag failed ` +
        `(submission ${submissionId}); the flag stays open for the reviewer`,
      error,
    )
  }
}
