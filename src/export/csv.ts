import type { Column } from './columns'
import type { ExportCell } from './rows'

/**
 * UTF-8 BOM первым символом файла. Данные не-ASCII с первой же строки
 * (провайдер «Çelebi», турецкие адреса, русские значения полей), а Excel —
 * самый частый СЛУЧАЙНЫЙ читатель .csv — считает файл без метки локальной
 * однобайтовой кодировкой и молча показывает «Ã‡elebi». Для заявленного
 * потребителя (импорт в смежную систему) метка бесплатна: Unicode прямо
 * разрешает ведущий BOM у UTF-8, и парсеры его отбрасывают. Это решение
 * НЕсимметрично решению о формулах ниже: BOM ничего не меняет в данных для
 * корректного читателя, а префикс-защита от формул меняет.
 */
const BOM = '﻿'

/**
 * Одна ячейка по RFC 4180: пусто для `null`, число как есть, строка — в
 * кавычках, только если содержит запятую, кавычку или перенос строки
 * (внутренние кавычки удваиваются). `\r` в проверке на всякий случай тоже:
 * значение с ним без кавычек развалило бы строку у CRLF-читателя.
 *
 * ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ — защиты от формул. Ячейку, начинающуюся с
 * `=`, `+`, `-`, `@`, Excel при открытии CSV исполняет, и обычная защита —
 * префикс `'` или таб. Она не применяется, потому что калечит данные для
 * того, кому файл адресован: назначение CSV — загрузка в смежные системы
 * (см. план 3), а телефоны операционных контактов (`II.1.2`, `II.2.1`,
 * `II.3.2`…) — легитимные значения, начинающиеся с «+» («+90 212 …»), и
 * принимающая система получила бы их с чужим символом впереди. Человеку же
 * выгрузка отдаёт xlsx (`workbook.ts`), где exceljs пишет строки инертными
 * строковыми ячейками, а не формулами. Решение закреплено тестом
 * (`__tests__/csv.test.ts`: телефон и `=SUM(…)` уезжают дословно) — если
 * когда-нибудь появится потребитель, ради которого защиту включают, тест
 * заставит сделать это осознанно, а не заодно.
 */
function escape(value: ExportCell): string {
  if (value === null) return ''
  if (typeof value === 'number') return String(value)
  return /[",\n\r]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value
}

/**
 * Плоская выгрузка в CSV. Разделитель строк — CRLF: так предписывает
 * RFC 4180, так пишет Excel, и любой LF-читатель CRLF тоже принимает —
 * обратное неверно. Внутренние переносы в значениях остаются как хранятся
 * (LF из textarea) — под кавычками они часть значения, а не разделитель.
 */
export function flatCsv(input: {
  columns: Column[]
  rows: ExportCell[][]
}): string {
  const header = input.columns.map((column) => escape(column.header)).join(',')
  const body = input.rows.map((row) => row.map(escape).join(','))
  return BOM + [header, ...body].join('\r\n')
}
